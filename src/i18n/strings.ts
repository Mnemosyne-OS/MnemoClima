/** de / pt / ru / zh live in more.ts; a key they leave out reads English. */
const DICTS: Record<Lang, Dict> = { en, fr, es, de, pt, ru, zh };

export function isLang(x: unknown): x is Lang {
  return typeof x === 'string' && (LANGS as readonly string[]).includes(x);
}

/** One string, in one language, with `{placeholders}` filled. A missing key reads English. */
export function translate(lang: Lang, key: Key, vars?: Record<string, string | number>): string {
  const s = DICTS[lang]?.[key] ?? en[key];
  if (!vars) return s;
  return s.replace(/\{(\w+)\}/g, (whole, name: string) => (name in vars ? String(vars[name]) : whole));
}

/** For the parity test: every written locale and its dictionary. */
export const WRITTEN: Record<'en' | 'fr' | 'es', Dict> = { en, fr, es };

/** A month in the language: "September 2026". */
export function monthName(lang: Lang, y: number, m: number, style: 'long' | 'short' = 'long'): string {
  try {
    return new Intl.DateTimeFormat(lang, { month: style, year: 'numeric', timeZone: 'UTC' }).format(new Date(Date.UTC(y, m - 1, 15)));
  } catch (err) {
    // an engine without this locale's data still gets a readable month
    console.warn('[MnemoClima] month not formatted', lang, err);
    return `${y}-${String(m).padStart(2, '0')}`;
  }
}

/** A day in the language: "8 October 2026". */
export function dayName(lang: Lang, iso: string): string {
  const t = Date.parse(iso.length === 10 ? `${iso}T12:00:00Z` : iso);
  if (Number.isNaN(t)) return iso;
  try {
    return new Intl.DateTimeFormat(lang, { day: 'numeric', month: 'long', year: 'numeric', timeZone: 'UTC' }).format(new Date(t));
  } catch (err) {
    console.warn('[MnemoClima] day not formatted', lang, err);
    return iso.slice(0, 10);
  }
}

/** A number with the language's decimal mark and an explicit sign when asked. */
export function fmt(lang: Lang, v: number, digits = 1, signed = false): string {
  const s = new Intl.NumberFormat(lang, { minimumFractionDigits: digits, maximumFractionDigits: digits }).format(Math.abs(v));
  if (!signed) return v < 0 ? `−${s}` : s;
  return v > 0 ? `+${s}` : v < 0 ? `−${s}` : s;
}
